// 【申请模板步骤】
// 1. 用小程序账号登录微信公众平台 https://mp.weixin.qq.com
//    （注意：订阅消息仅企业认证主体可用，个人主体小程序无此功能）
// 2. 左侧菜单进入：功能 → 订阅消息 → 公共模板库
// 3. 按关键词搜索合适模板并「选用」，建议三个角色各选一个：
//      - user（报修用户）：搜「报修」「进度」「维修进度」→ 如「报修进度通知」
//      - repairer（维修人员）：搜「任务」「指派」→ 如「任务提醒/新任务通知」
//      - admin（管理员）：搜「新订单」「待办」→ 如「新工单提醒」
// 4. 选用后在「我的模板」页能看到每个模板的【模板ID】（一串字母数字）
// 5. 把模板ID填入下方 TEMPLATE_IDS 对应角色；留空则该角色推送自动跳过
//
// 【两处配置必须一致】
//   - 本文件（前端：决定向用户请求订阅哪个模板）
//   - cloudfunctions/orders/subscribe.js（云端：决定发送时用哪个模板及字段关键词）
//   两边填同一个模板ID。改完需重新上传小程序代码 + 重新部署 orders 云函数。
//
// 【字段关键词】
// 模板自带若干固定字段（如 服务名称/进度详情/处理时间）。
// 点「我的模板」中该模板的【详情】，每个字段右侧标注关键词
// （thing1、thing2、phrase3、time4 之类），将其填到
// cloudfunctions/orders/subscribe.js 的 titleField / contentField 中即可。
module.exports = {
  TEMPLATE_IDS: {
    user: '',      // 报修用户：工单进度通知（填入模板ID）
    repairer: '',  // 维修人员：新任务/验收结果通知（填入模板ID）
    admin: ''      // 管理员：新工单/维修完成提醒（填入模板ID）
  }
};
